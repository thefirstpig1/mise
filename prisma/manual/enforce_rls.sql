-- ============================================================
-- Mise — make RLS actually enforce  (Sprint 7 Part 30, ADR 0030)
-- ============================================================
-- RUN THIS BY HAND, AS THE TABLE OWNER (neondb_owner), VIA DIRECT_URL.
-- It is NOT a Prisma migration and must not be moved into prisma/migrations/
-- (Sprint 0 convention, and it manages a ROLE, which migrations must not).
--
-- WHAT IS WRONG TODAY, MEASURED RATHER THAN ASSUMED:
--
--     connecting role : neondb_owner — rolbypassrls TRUE, owns the tables TRUE
--     54 tables · RLS enabled 47 · RLS FORCED 0 · policies 47
--
-- Row-level security has been ENABLED since Sprint 0 and has never filtered a
-- single row, because the application connects as a role that bypasses it
-- twice over. ADR 0004 Consequence 3 recorded this in Sprint 1 and deferred
-- the fix to Sprint 7 by name.
--
-- WHY `FORCE ROW LEVEL SECURITY` IS NOT THE FIX ON ITS OWN. FORCE removes the
-- OWNER's bypass. It does nothing about the `BYPASSRLS` ATTRIBUTE, which
-- neondb_owner also carries (Neon grants it neon_superuser). Section 3 below
-- would be forty-seven no-ops without section 1.
--
-- ORDER MATTERS. Sections 1 and 2 are safe to run at any time: they create a
-- role nothing is using yet. Section 3 and 4 are the switch, and the moment
-- DATABASE_URL points at mise_app the policies start filtering for real.
--
-- 🛑 BEFORE RUNNING SECTION 3-4, THE APPLICATION CODE MUST ALREADY BE ON THE
--    Part 30 L1+ changes. Running them against today's code will:
--      * make it impossible to create a new shop (createTenant writes seven
--        rows before the tenant exists, and the `tenant` policy's USING acts
--        as WITH CHECK)
--      * break login (require-tenant.ts discovers the tenant by userId, with
--        no tenant context to discover it in)
--    Sections 1-2 first, then the code, then 3-4.
-- ============================================================


-- ============================================================
-- 1. The application role
-- ============================================================
-- Not the owner of anything, and no BYPASSRLS. That combination is what makes
-- the forty-seven existing policies apply at all — it is the whole fix.
--
-- ⚠️ REPLACE THE PASSWORD BELOW BEFORE RUNNING, AND DO NOT COMMIT THE FILLED
--    VERSION. Generate one that is long and random; it goes into DATABASE_URL
--    and nowhere else.

CREATE ROLE mise_app WITH LOGIN PASSWORD 'REPLACE_ME_BEFORE_RUNNING';

-- Neon puts every role in the `neon_superuser` group by default in some
-- setups; that group carries BYPASSRLS and would silently undo this whole
-- file. Revoking is harmless if it was never granted.
REVOKE neon_superuser FROM mise_app;

-- ⚠️ THERE IS NO `ALTER ROLE ... NOSUPERUSER` HERE, AND THAT IS DELIBERATE.
-- The obvious belt-and-braces line
--
--     ALTER ROLE mise_app NOBYPASSRLS NOSUPERUSER NOCREATEDB NOCREATEROLE;
--
-- CANNOT RUN on Neon: neondb_owner is not a superuser, and Postgres answers
-- "Only roles with the SUPERUSER attribute may change the SUPERUSER attribute".
-- In a pasted batch that error stops every statement after it — which is
-- exactly what happened the first time this file was run, leaving a role that
-- could log in and had no grants at all.
--
-- It is also unnecessary: a role created by SQL gets NOSUPERUSER and
-- NOBYPASSRLS by default. Verify rather than assert (section 5).


-- ============================================================
-- 2. What the application role may do
-- ============================================================
-- DML only. No DDL: migrations keep running as the owner through DIRECT_URL,
-- so the role the internet can reach cannot alter a table.

GRANT USAGE ON SCHEMA public TO mise_app;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON ALL TABLES IN SCHEMA public TO mise_app;

-- Prisma's own bookkeeping is the owner's business. The app never reads it,
-- and a role that can rewrite migration history is a role that can lie about
-- what shape the database is in.
REVOKE ALL ON TABLE "_prisma_migrations" FROM mise_app;

-- THE LINE THAT MATTERS SIX MONTHS FROM NOW. Without it, the first table a
-- future Part adds is invisible to the application — and the failure arrives
-- as "permission denied for table staff_roster" on a screen, long after the
-- migration that looked fine.
ALTER DEFAULT PRIVILEGES FOR ROLE neondb_owner IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO mise_app;

-- No sequence grants: every id in this schema is a uuid or a cuid generated by
-- the application or by gen_random_uuid(), and nothing uses a serial. If that
-- ever changes, sequences need USAGE here too.


