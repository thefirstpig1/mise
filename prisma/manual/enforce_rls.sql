-- ============================================================
-- 4. Policies that refuse to be polite about a missing context
-- ============================================================
-- Every policy reads `current_setting('app.current_tenant_id', true)`, and
-- that `true` means "return NULL instead of raising when it is unset". NULL
-- makes the comparison false, so a query with no tenant context returns ZERO
-- ROWS, silently — the shop phones to say the data has disappeared, and the
-- investigation starts at the data.
--
-- Dropping the flag turns that into an error, in development, where it is a
-- bug. This is rule A8 one level up: ADR 0029 refused to let "you may not see
-- this" render as ฿0, because absence and refusal are different facts.
--
-- ALTER rather than DROP + CREATE: a dropped policy is a table with no policy,
-- and if this file fails halfway through, that table is wide open.
--
-- All forty-seven are `FOR ALL` with no separate WITH CHECK, so Postgres uses
-- the USING expression for inserts and updates too — which is why section 4
-- alone governs both what can be read and what can be written.

ALTER POLICY tenant_isolation ON "branch" USING ((tenant_id = (current_setting('app.current_tenant_id'::text))::uuid));
