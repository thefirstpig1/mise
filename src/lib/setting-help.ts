// ============================================================
// Mise — what each shop setting means, for the "?" beside it
// ============================================================
// Friend's-shop feedback (Kong 2026-10-31): the first setup used words a
// shop could not read — "% of what?", "what does this line do?" — and nothing
// said which screen a number would move. Mockup 1wgaH9Jfx8L7CxqfNHtdn3 gave
// every setting four answers: what it is, an example in baht, the pages it
// changes (traced from the code that reads it, not guessed), and what
// changing it does to records already made.
//
// Round 2 (Kong 2026-11-01, mockup 225p68BDqKAZTpd9MqDeph): "ต้องทำให้ชัดเจน
// เห็นภาพกว่านี้" → "แบบหนังสือเรียน เอาง่ายๆ". Every setting now has a picture
// (src/components/ui/help-pictures.tsx); `example` is the caption under it, and
// the rest was cut to a sentence each — help boxes that run past three
// sentences stop being read (PatternFly / SAP popover guidance).
//
// A plain module so the signup page, the settings page (a Server Component)
// and the branch form (a client one) can all read it. Keyed by the form field
// name; the title is the question the field asks.
// ============================================================

